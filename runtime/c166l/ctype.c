static unsigned char character_class(int character)
{
  if ((unsigned int)character > 255U)
    return 0;
  return _ctype_[(unsigned int)character + 1U];
}

int isalpha(int character)
{
  return character_class(character) & (CTYPE_UPPER | CTYPE_LOWER);
}

int isupper(int character)
{
  return character_class(character) & CTYPE_UPPER;
}

int islower(int character)
{
  return character_class(character) & CTYPE_LOWER;
}

int isdigit(int character)
{
  return character_class(character) & CTYPE_NUMBER;
}

int isxdigit(int character)
{
  return character_class(character) & (CTYPE_NUMBER | CTYPE_HEX);
}

int isspace(int character)
{
  return character_class(character) & (CTYPE_SPACE | CTYPE_WHITESPACE);
}

int ispunct(int character)
{
  return character_class(character) & CTYPE_PUNCTUATION;
}

int isalnum(int character)
{
  return character_class(character) &
      (CTYPE_UPPER | CTYPE_LOWER | CTYPE_NUMBER);
}

int isprint(int character)
{
  return character_class(character) &
      (CTYPE_PUNCTUATION | CTYPE_UPPER | CTYPE_LOWER |
       CTYPE_NUMBER | CTYPE_SPACE);
}

int isgraph(int character)
{
  return character_class(character) &
      (CTYPE_PUNCTUATION | CTYPE_UPPER | CTYPE_LOWER | CTYPE_NUMBER);
}

int iscntrl(int character)
{
  return character_class(character) & (CTYPE_CONTROL | CTYPE_WHITESPACE);
}

int isascii(int character)
{
  return (unsigned int)character <= 127U;
}

int toascii(int character)
{
  return character & 127;
}

int toupper(int character)
{
  if (character >= 'a' && character <= 'z')
    return character - 'a' + 'A';
  return character;
}

int tolower(int character)
{
  if (character >= 'A' && character <= 'Z')
    return character - 'A' + 'a';
  return character;
}
